// Rasterize mermaid Unicode art to a PNG so [Open Image] has a real file,
// matching the Rust pager's on-disk PNG contract (never inline Kitty graphics).
func writeMermaidPNG(art string, out string, dark bool, quality string) error {
	lines := strings.Split(strings.TrimRight(art, "\n"), "\n")
	if len(lines) == 0 {
		lines = []string{"(empty diagram)"}
	}
	cellW, cellH := 8, 14
	if quality == "open" {
		cellW, cellH = 14, 24
	}
	maxCols := 1
	for _, ln := range lines {
		if n := utf8.RuneCountInString(ln); n > maxCols {
			maxCols = n
		}
	}
	pad := 16
	w := pad*2 + maxCols*cellW
	h := pad*2 + len(lines)*cellH
	if w < 64 {
		w = 64
	}
	if h < 48 {
		h = 48
	}
	bg, fg := color.RGBA{0x1E, 0x1E, 0x2E, 0xFF}, color.RGBA{0xCD, 0xD6, 0xF4, 0xFF}
	if !dark {
		bg, fg = color.RGBA{0xEF, 0xF1, 0xF5, 0xFF}, color.RGBA{0x4C, 0x4F, 0x69, 0xFF}
	}
	img := image.NewRGBA(image.Rect(0, 0, w, h))
	for y := 0; y < h; y++ {
		for x := 0; x < w; x++ {
			img.SetRGBA(x, y, bg)
		}
	}
	for row, ln := range lines {
		col := 0
		for _, r := range ln {
			if r != ' ' {
				drawGlyph(img, pad+col*cellW, pad+row*cellH, cellW, cellH, r, fg)
			}
			col++
		}
	}
	f, err := os.OpenFile(out, os.O_CREATE|os.O_WRONLY|os.O_TRUNC, 0o600)
	if err != nil {
		return err
	}
	defer f.Close()
	return png.Encode(f, img)
}

func drawGlyph(img *image.RGBA, x, y, cw, ch int, r rune, fg color.RGBA) {
	bits := glyphBits(r)
	gw, gh := 5, 7
	scaleX := max(1, (cw-2)/gw)
	scaleY := max(1, (ch-2)/gh)
	ox := x + (cw-gw*scaleX)/2
	oy := y + (ch-gh*scaleY)/2
	for gy := 0; gy < gh; gy++ {
		row := bits[gy]
		for gx := 0; gx < gw; gx++ {
			if row&(1<<uint(4-gx)) == 0 {
				continue
			}
			for sy := 0; sy < scaleY; sy++ {
				for sx := 0; sx < scaleX; sx++ {
					img.SetRGBA(ox+gx*scaleX+sx, oy+gy*scaleY+sy, fg)
				}
			}
		}
	}
}

func glyphBits(r rune) [7]byte {
	if r >= 0x20 && r <= 0x7e {
		return asciiGlyphs[r-0x20]
	}
	// Box-drawing / arrows used by the ASCII mermaid layout.
	switch r {
	case '─', '━', '—':
		return [7]byte{0x00, 0x00, 0x00, 0x1F, 0x00, 0x00, 0x00}
	case '│', '┃', '|':
		return [7]byte{0x04, 0x04, 0x04, 0x04, 0x04, 0x04, 0x04}
	case '┌', '╭':
		return [7]byte{0x00, 0x00, 0x00, 0x07, 0x04, 0x04, 0x04}
	case '┐', '╮':
		return [7]byte{0x00, 0x00, 0x00, 0x1C, 0x04, 0x04, 0x04}
	case '└', '╰':
		return [7]byte{0x04, 0x04, 0x04, 0x07, 0x00, 0x00, 0x00}
	case '┘', '╯':
		return [7]byte{0x04, 0x04, 0x04, 0x1C, 0x00, 0x00, 0x00}
	case '├':
		return [7]byte{0x04, 0x04, 0x04, 0x07, 0x04, 0x04, 0x04}
	case '┤':
		return [7]byte{0x04, 0x04, 0x04, 0x1C, 0x04, 0x04, 0x04}
	case '┬':
		return [7]byte{0x00, 0x00, 0x00, 0x1F, 0x04, 0x04, 0x04}
	case '┴':
		return [7]byte{0x04, 0x04, 0x04, 0x1F, 0x00, 0x00, 0x00}
	case '┼':
		return [7]byte{0x04, 0x04, 0x04, 0x1F, 0x04, 0x04, 0x04}
	case '▼', '↓':
		return [7]byte{0x04, 0x04, 0x04, 0x1F, 0x0E, 0x04, 0x00}
	case '▲', '↑':
		return [7]byte{0x00, 0x04, 0x0E, 0x1F, 0x04, 0x04, 0x04}
	case '►', '→', '▸':
		return [7]byte{0x00, 0x04, 0x06, 0x1F, 0x06, 0x04, 0x00}
	case '◄', '←':
		return [7]byte{0x00, 0x04, 0x0C, 0x1F, 0x0C, 0x04, 0x00}
	case '◇', '◆':
		return [7]byte{0x04, 0x0A, 0x11, 0x0A, 0x04, 0x00, 0x00}
	}
	return [7]byte{0x1F, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1F}
}

